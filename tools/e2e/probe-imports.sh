#!/usr/bin/env bash
# Risk probe for the real plugin-suite integration shape:
# a plugin inserted by ABSOLUTE FILESYSTEM PATH whose host half imports
# `@deepseek-ai/*` runtime packages.
#
# The probe runs twice and prints both reports:
#
#   1. BASELINE (no linked root): bare imports resolve to the repo's own pnpm
#      copies. The plugin still mounts and functions, but the process now holds
#      a second copy of cordis/dsh-llm/dsh-session (`ctx instanceof Context` is
#      false), which is a fragile identity split for real plugins.
#   2. WORKAROUND (repo registered as a linked root via link-repo-root.sh):
#      imports resolve to the DSH installation's copies, identity checks pass,
#      and service mount interop is verified.
#
# PASS requires the workaround report to be fully green. The baseline is
# reported as evidence, not as a failure (a future DSH may legitimately change
# its behavior).
#
# Usage: tools/e2e/probe-imports.sh
# Requires: repo `pnpm install` (node_modules/@deepseek-ai/cordis present).
set -euo pipefail

# shellcheck source=lib/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

PROBE_DIR="${E2E_DIR}/fixtures/import-probe-plugin"
PROBE_OUT_DIR="${DSH_E2E_ROOT}/smoke"
BASELINE_OUT="${PROBE_OUT_DIR}/import-probe-baseline.json"
WORKAROUND_OUT="${PROBE_OUT_DIR}/import-probe-workaround.json"
LINK_DIR="${DSH_HOME}/profiles/${DSH_E2E_PROFILE}/node_modules"
LINK_NAME="${DSH_E2E_REPO_LINK_NAME:-e2e-repo-root}"

cleanup() {
  local code=$?
  if [[ "${DSH_E2E_KEEP_RUNNING:-0}" == "1" ]]; then
    echo "e2e probe: keeping the isolated instance running: $(cat "${STATE_DIR}/web.url" 2>/dev/null || true)"
    return 0
  fi
  "${E2E_DIR}/stop-web.sh" >/dev/null 2>&1 || true
  return "${code}"
}
trap cleanup EXIT

if [[ ! -d "${REPO_ROOT}/node_modules/@deepseek-ai/cordis" ]]; then
  echo "e2e probe: ${REPO_ROOT}/node_modules/@deepseek-ai/cordis is missing; run 'pnpm install' in the repo first" >&2
  exit 2
fi
[[ -f "${PROBE_DIR}/index.js" ]] || { echo "e2e probe: missing ${PROBE_DIR}/index.js" >&2; exit 2; }

echo "e2e probe: repo node_modules copy:"
node -e 'console.log("  " + require("node:fs").realpathSync(process.argv[1]))' "${REPO_ROOT}/node_modules/@deepseek-ai/cordis"
echo "e2e probe: DSH installation runtime version:"
"${DSH_BIN}" --version | sed 's/^/  /'

"${E2E_DIR}/bootstrap.sh" >/dev/null
mkdir -p "${PROBE_OUT_DIR}" "${LINK_DIR}"
cat >"${CONFIG_DIR}/import-probe.patch.yml" <<EOF
# Generated by tools/e2e/probe-imports.sh — do not edit by hand.
- insert:
    - id: e2e-import-probe-plugin
      name: ${PROBE_DIR}/index.js
EOF

# Boot once with a given probe description and write the health payload.
# usage: run_probe <label> <outfile>
run_probe() {
  local label="$1" outfile="$2"
  "${E2E_DIR}/start-web.sh" "${CONFIG_DIR}/import-probe.patch.yml" >/dev/null 2>&1
  curl -fsS "http://${DSH_E2E_HOST}:${DSH_E2E_WEB_PORT}/e2e-import-probe/health" -o "${outfile}" || {
    echo "e2e probe: ${label} — plugin did not mount; see ${LOG_DIR}/web.log" >&2
    tail -n 60 "${LOG_DIR}/web.log" >&2 || true
    return 1
  }
  echo
  echo "=== ${label} ==="
  "${DSH_E2E_NODE}" -e '
    const report = JSON.parse(require("node:fs").readFileSync(process.argv[1], "utf8"))
    console.log(JSON.stringify(report, null, 2))
  ' "${outfile}"
  "${E2E_DIR}/stop-web.sh" >/dev/null 2>&1 || true
}

# ---------------------------------------------------------- 1) baseline ----
rm -f "${LINK_DIR}/${LINK_NAME}"
run_probe "BASELINE: direct absolute-path import (no linked root)" "${BASELINE_OUT}"

# ------------------------------------------------------ 2) workaround ------
"${E2E_DIR}/link-repo-root.sh" >/dev/null
run_probe "WORKAROUND: repo registered as a linked root" "${WORKAROUND_OUT}"

# -------------------------------------------------------------- verdict ----
echo
"${DSH_E2E_NODE}" -e '
  const fs = require("node:fs")
  const baseline = JSON.parse(fs.readFileSync(process.argv[1], "utf8"))
  const workaround = JSON.parse(fs.readFileSync(process.argv[2], "utf8"))
  const ok = workaround.ok === true
  console.log("baseline : repoCopy=" + baseline.resolutionFromRepoCopy
    + " installationCopy=" + baseline.resolutionFromInstallation
    + " contextIdentity=" + baseline.contextIdentity
    + " checks=" + JSON.stringify(baseline.checks))
  console.log("workaround: repoCopy=" + workaround.resolutionFromRepoCopy
    + " installationCopy=" + workaround.resolutionFromInstallation
    + " contextIdentity=" + workaround.contextIdentity
    + " checks=" + JSON.stringify(workaround.checks))
  if (!ok) {
    console.error("e2e probe: FAIL — the linked-root workaround did not produce a fully green report")
    process.exit(1)
  }
  console.log("e2e probe: PASS — absolute-path plugins resolve @deepseek-ai/* to the DSH installation when the repo is a linked root")
' "${BASELINE_OUT}" "${WORKAROUND_OUT}"
