#!/usr/bin/env bash
# End-to-end verification of the REAL infini-goal plugin suite against the
# installed DeepSeek Harness 0.2.2-rc.1, inside the isolated harness.
#
# What it does:
#   1. builds the repo (`pnpm build`) so every plugin package has lib/*.js,
#   2. generates the development overlay `node scripts/dev-patch.mjs`
#      (`.tmp/cordis.patch.yml`, absolute built entry paths for the 5 plugin rows),
#   3. prepares the isolated DSH home + custom `web`-template profile,
#   4. registers the repo checkout as a linked root of the isolated profile
#      (link-repo-root.sh), so the plugin bundles' `@deepseek-ai/*` imports
#      resolve to the DSH installation's single copies,
#   5. inserts the E2E control plugin (absolute path) that drives
#      `ctx.infiniGoals` directly and streams its state over HTTP,
#   6. boots the isolated Web instance with a deterministic mock LLM,
#   7. runs the pacing / quiet-window / pause scenarios (suite-drive.mjs),
#      observing durable `user/message` events whose source kind is
#      `infini-goal`,
#   8. stops the instance and prints a PASS/FAIL summary.
#
# Usage:
#   tools/e2e/suite.sh                 # build + boot + all scenarios
#   tools/e2e/suite.sh --fresh         # ... from a pristine isolated DSH home
#   tools/e2e/suite.sh --only scenario1,scenario3
#   DSH_E2E_KEEP_RUNNING=1 tools/e2e/suite.sh   # leave the instance for poking
#
# Requirements: pnpm + the repo's node_modules installed, ports >= 34000 free.
set -euo pipefail

# shellcheck source=lib/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

FRESH=0
ONLY=""
while (( $# > 0 )); do
  case "$1" in
    --fresh) FRESH=1; shift ;;
    --only)
      [[ $# -ge 2 ]] || { echo "e2e suite: --only needs a value" >&2; exit 2; }
      ONLY="$2"; shift 2 ;;
    -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "e2e suite: unknown argument $1" >&2; exit 2 ;;
  esac
done

SUITE_DIR="${DSH_E2E_ROOT}/suite"
CONTROL_PATCH="${CONFIG_DIR}/control-plugin.patch.yml"
SUITE_PATCH="${REPO_ROOT}/.tmp/cordis.patch.yml"

PASS_STEPS=0
step() { PASS_STEPS=$((PASS_STEPS + 1)); printf '\n=== [%d] %s ===\n' "${PASS_STEPS}" "$*"; }
fail() { echo "SUITE FAIL: $*" >&2; exit 1; }

cleanup() {
  local code=$?
  if [[ "${DSH_E2E_KEEP_RUNNING:-0}" == "1" ]]; then
    echo ""
    echo "e2e suite: DSH_E2E_KEEP_RUNNING=1 — leaving the isolated instance running"
    echo "e2e suite:   browser URL: $(cat "${STATE_DIR}/web.url" 2>/dev/null || echo '<not started>')"
    echo "e2e suite:   stop with:  ${E2E_DIR}/stop-web.sh"
    return 0
  fi
  "${E2E_DIR}/stop-web.sh" >/dev/null 2>&1 || true
  return "${code}"
}
trap cleanup EXIT

e2e_assert_ports
e2e_require_launcher
e2e_require_file "${E2E_DIR}/fixtures/e2e-control-plugin/index.js"
e2e_require_file "${E2E_DIR}/link-repo-root.sh"
e2e_require_file "${E2E_DIR}/suite-drive.mjs"
mkdir -p "${SUITE_DIR}"
if ! command -v pnpm >/dev/null 2>&1; then
  fail "pnpm is required on PATH to build the plugin suite"
fi

# A --fresh run wipes the scratch root, so do that before writing any artifact.
if (( FRESH )); then
  "${E2E_DIR}/bootstrap.sh" --fresh >/dev/null
fi
mkdir -p "${SUITE_DIR}"

# ------------------------------------------------------------------ build --
step "build the plugin suite (pnpm build)"
(
  cd "${REPO_ROOT}"
  pnpm build
) >"${SUITE_DIR}/build.log" 2>&1 || {
  tail -n 40 "${SUITE_DIR}/build.log" >&2
  fail "pnpm build failed"
}
tail -n 3 "${SUITE_DIR}/build.log" | sed 's/^/  /'
[[ -f "${REPO_ROOT}/packages/infini-goal/lib/index.js" ]] || fail "missing built host entry packages/infini-goal/lib/index.js"
echo "PASS build complete"

# -------------------------------------------------------------- dev patch --
step "generate the development overlay (scripts/dev-patch.mjs)"
(
  cd "${REPO_ROOT}"
  node scripts/dev-patch.mjs
) >"${SUITE_DIR}/dev-patch.log" 2>&1 || {
  tail -n 40 "${SUITE_DIR}/dev-patch.log" >&2
  fail "scripts/dev-patch.mjs failed"
}
[[ -f "${SUITE_PATCH}" ]] || fail "dev-patch did not write ${SUITE_PATCH}"
grep -q 'packages/infini-goal/lib/index.js' "${SUITE_PATCH}" || fail "dev patch does not insert the infini-goal host entry"
grep -c 'name: ' "${SUITE_PATCH}" | xargs -I{} echo "  rows inserted: {}"
echo "PASS ${SUITE_PATCH}"

# --------------------------------------------------------------- bootstrap --
step "prepare isolated DSH home, profile, mock LLM config"
"${E2E_DIR}/bootstrap.sh" >/dev/null
echo "PASS DSH_HOME=${DSH_HOME} profile=${DSH_E2E_PROFILE}"

# ------------------------------------------------------------ linked root --
step "register repo checkout as a linked root (single @deepseek-ai/* copy)"
"${E2E_DIR}/link-repo-root.sh"
cat >"${CONTROL_PATCH}" <<EOF
# Generated by tools/e2e/suite.sh — do not edit by hand.
# E2E control plugin: drives ctx.infiniGoals over plain HTTP routes. Only added
# in the suite run, never in the trivial smoke.
- insert:
    - id: e2e-control-plugin
      name: ${E2E_DIR}/fixtures/e2e-control-plugin/index.js
EOF
echo "PASS linked root + control plugin patch"

# ------------------------------------------------------------------- boot --
step "boot isolated web instance with the plugin suite + control plugin"
# The mock LLM answers every model request with a deterministic echo: the
# scenarios need no special completions, just a terminating turn.
cat >"${CONFIG_DIR}/scenario-suite.json" <<'EOF'
{
  "responses": []
}
EOF
DSH_E2E_SCENARIO="${CONFIG_DIR}/scenario-suite.json" \
  "${E2E_DIR}/start-web.sh" "${SUITE_PATCH}" "${CONTROL_PATCH}"
WEB_URL="$(cat "${STATE_DIR}/web.url")"
WEB_BASE="http://${DSH_E2E_HOST}:${DSH_E2E_WEB_PORT}"
grep -q '\[e2e-control-plugin\]' "${LOG_DIR}/web.log" || true
echo "PASS readiness url=${WEB_URL}"

# ------------------------------------------------------- composition check --
step "plugin suite is composed in the isolated instance"
HEALTH="$(curl -fsS "${WEB_BASE}/e2e-infini/health")" || fail "control plugin unreachable — did ctx.infiniGoals mount?"
echo "  control health: ${HEALTH}"
echo "${HEALTH}" | grep -q '"hasInfiniGoals":true' || fail "control plugin mounted without ctx.infiniGoals"
"${DSH_E2E_NODE}" "${E2E_DIR}/probe-web.mjs" \
  --state-dir "${STATE_DIR}" \
  --assert-client-entry @yankeguo/dsh-client-ui-infini-goal \
  --assert-client-bundle @yankeguo/dsh-client-ui-infini-goal \
  >"${SUITE_DIR}/probe-web.log" 2>&1 || {
    cat "${SUITE_DIR}/probe-web.log" >&2
    fail "client-ui package missing from window.__DSH_BOOT__"
  }
grep -E 'client entry @yankeguo/dsh-client-ui-infini-goal' "${SUITE_DIR}/probe-web.log" | sed 's/^/  /'
echo "PASS host service + browser client row composed"

# -------------------------------------------------------------- scenarios --
step "run infini-goal scenarios (pacing, quiet window, pause)"
DRIVE_ARGS=(--state-dir "${STATE_DIR}" --workspace "${WORKSPACE_DIR}")
if [[ -n "${ONLY}" ]]; then
  DRIVE_ARGS+=(--only "${ONLY}")
fi
"${DSH_E2E_NODE}" "${E2E_DIR}/suite-drive.mjs" "${DRIVE_ARGS[@]}" 2>&1 | tee "${SUITE_DIR}/scenarios.log"
# tee hides the producer's exit status; re-check the summary line.
grep -q 'SUITE SCENARIOS PASS' "${SUITE_DIR}/scenarios.log" || fail "scenario driver reported failures (see ${SUITE_DIR}/scenarios.log)"
echo "PASS all suite scenarios"

# ------------------------------------------------------------- shutdown ----
step "clean shutdown"
if [[ "${DSH_E2E_KEEP_RUNNING:-0}" == "1" ]]; then
  echo "SKIP stopped (DSH_E2E_KEEP_RUNNING=1); browser URL: ${WEB_URL}"
else
  "${E2E_DIR}/stop-web.sh" >/dev/null
  echo "PASS stopped"
fi

step "summary"
echo "SUITE PASS (${PASS_STEPS} steps)"
echo "  isolated home : ${DSH_HOME}"
echo "  web URL       : ${WEB_URL}"
echo "  artifacts     : ${SUITE_DIR}"
