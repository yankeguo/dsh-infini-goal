#!/usr/bin/env bash
# Prepare the isolated E2E harness: a throwaway DSH_HOME under /tmp, a custom
# `e2e` profile cloned from the shipped `web` template, and the generated
# patch overlays (mock LLM provider + trivial fixture plugin).
#
# Nothing under the user's real ~/.dsh is read or written. The running Desktop
# app is never touched: this script only invokes the packaged CLI in its
# `--dump-config` (boot-free) mode.
#
# Usage:
#   tools/e2e/bootstrap.sh [--fresh]
#
#   --fresh   delete ${DSH_E2E_ROOT} first (refused unless the path is /tmp/...)
#
# Environment: see lib/common.sh.
set -euo pipefail

# shellcheck source=lib/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

FRESH=0
for arg in "$@"; do
  case "${arg}" in
    --fresh) FRESH=1 ;;
    -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "e2e bootstrap: unknown argument ${arg}" >&2; exit 2 ;;
  esac
done

e2e_assert_ports
e2e_require_launcher

if (( FRESH )); then
  # Safety: only ever remove a scratch root inside /tmp, never a real home.
  case "${DSH_E2E_ROOT}" in
    /tmp/*) ;;
    *) echo "e2e bootstrap: refusing --fresh for DSH_E2E_ROOT=${DSH_E2E_ROOT} (must live under /tmp)" >&2; exit 2 ;;
  esac
  rm -rf "${DSH_E2E_ROOT}"
fi

e2e_mkdirs

echo "e2e: root       ${DSH_E2E_ROOT}"
echo "e2e: DSH_HOME   ${DSH_HOME}"
echo "e2e: profile    ${DSH_E2E_PROFILE} (from shipped 'web' template)"
echo "e2e: web port   ${DSH_E2E_WEB_PORT}"
echo "e2e: llm port   ${DSH_E2E_LLM_PORT}"

# ---------------------------------------------------------------- profile --
if e2e_have_profile; then
  echo "e2e: profile already exists, keeping it"
else
  echo "e2e: creating custom profile from the shipped web template"
  (
    cd "${WORKSPACE_DIR}"
    DSH_HOME="${DSH_HOME}" "${DSH_BIN}" "${DSH_E2E_PROFILE}" \
      --from-default-profile web --dump-config
  ) >"${LOG_DIR}/profile-dump.yml" 2>"${LOG_DIR}/profile.log" || {
    echo "e2e: profile creation failed; see ${LOG_DIR}/profile.log" >&2
    tail -n 40 "${LOG_DIR}/profile.log" >&2 || true
    exit 1
  }
fi

# ------------------------------------------------------- generated patches --
# 1) Mock model route + default model + deterministic title path.
cat >"${CONFIG_DIR}/mock-llm.patch.yml" <<EOF
# Generated by tools/e2e/bootstrap.sh — do not edit by hand.
#
# Routes every model request of the isolated instance at the deterministic mock
# server: a hand-declared 'mock' provider on pi-ai's openai-completions wire
# protocol (POST ${DSH_E2E_HOST}:${DSH_E2E_LLM_PORT}/v1/chat/completions, SSE).
# The credential reference must resolve (the launcher exports
# MOCK_LLM_API_KEY=sk-e2e-placeholder); a keyless OpenAI-compatible route is
# still required by pi-ai to carry some key.
- id: llm-pi-ai
  name: "@deepseek-ai/dsh-llm-pi-ai"
  config:
    providers:
      mock:
        displayName: E2E Mock LLM
        api: openai-completions
        baseURL: http://${DSH_E2E_HOST}:${DSH_E2E_LLM_PORT}/v1
        apiKeyEnv: MOCK_LLM_API_KEY
        models:
          - id: mock-model
            name: Mock Model
            contextWindow: 100000
            maxTokens: 8192
            input:
              - text
- id: agent-default-model
  name: "@deepseek-ai/dsh-agent-default-model"
  config:
    provider: mock
    model: mock-model
# The first-prompt LLM titler makes an auxiliary model request that would
# consume one scripted mock step; let the deterministic fallback title path run
# instead. (Session/title events still appear in the log.)
- id: session-title-llm
  name: "@deepseek-ai/dsh-session-title-first-prompt-llm"
  disabled: true
EOF

# 2) Keep the instance's first-use Workspace under the scratch root.
# The Web bundle creates a default workspace at
# `<Documents>/deepseek-harness/default-workspace` on first use; override the
# Documents directory so a UI-created Session never lands in the user's real
# Documents folder. (`documentsDirectory` is a Host-side config of the
# workspace controller row.)
cat >"${CONFIG_DIR}/isolation.patch.yml" <<EOF
# Generated by tools/e2e/bootstrap.sh — do not edit by hand.
- id: workspace-controller
  name: "@deepseek-ai/dsh-api-workspace-controller"
  config:
    documentsDirectory: ${DSH_E2E_ROOT}/documents
EOF

# 3) Trivial dual-face fixture plugin inserted by ABSOLUTE FILESYSTEM PATH.
cat >"${CONFIG_DIR}/trivial-plugin.patch.yml" <<EOF
# Generated by tools/e2e/bootstrap.sh — do not edit by hand.
#
# Proves the harness inserts a plugin by absolute filesystem path: this is the
# repo's hand-written fixture package, not a published npm package. Its host
# half registers GET /e2e-trivial/health on the isolated Web server; its client
# half (exports["./client"]) enters window.__DSH_BOOT__ and marks the DOM.
- insert:
    - id: e2e-trivial-plugin
      name: ${E2E_DIR}/fixtures/trivial-plugin/index.js
      config:
        marker: smoke
EOF

# 4) Default deterministic scenario consumed in order by the mock server.
cat >"${CONFIG_DIR}/scenario.json" <<'EOF'
{
  "responses": [
    {
      "kind": "text",
      "text": "MOCK E2E first turn",
      "chunks": ["MOCK E2E ", "first ", "turn"]
    },
    {
      "kind": "tool_call",
      "tool": "bash",
      "arguments": {
        "command": "printf e2e-tool-ok",
        "description": "echo the deterministic E2E marker"
      }
    },
    {
      "kind": "text",
      "text": "MOCK E2E final turn"
    }
  ]
}
EOF

echo "e2e: wrote ${CONFIG_DIR}/mock-llm.patch.yml"
echo "e2e: wrote ${CONFIG_DIR}/isolation.patch.yml"
echo "e2e: wrote ${CONFIG_DIR}/trivial-plugin.patch.yml"
echo "e2e: wrote ${CONFIG_DIR}/scenario.json"
echo "e2e: bootstrap complete"
