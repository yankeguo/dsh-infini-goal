#!/usr/bin/env node
/**
 * Generate a DSH profile patch overlay that inserts every built infini-goal
 * plugin by absolute filesystem path.
 *
 * This is the development/E2E path: it needs no npm publishing and no profile
 * dependency install. Boot a profile with:
 *
 *   dsh web --patch .tmp/cordis.patch.yml --port 34000 --no-open
 *
 * The generated patch keeps user-configurable defaults in one place; edit the
 * emitted file if you want a different minimum interval or quiet windows.
 *
 * Paths are emitted as YAML double-quoted scalars (JSON is a YAML subset), so a
 * checkout living under a directory with spaces or YAML-significant characters
 * still produces a loadable patch.
 */
import { existsSync } from 'node:fs'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, '.tmp', 'cordis.patch.yml')

/** One inserted Loader row. */
const ROWS = [
  { id: 'infini-goal', dir: 'infini-goal', config: { defaultMinIntervalMs: 60_000, defaultQuietWindows: [] } },
  { id: 'infini-goal-driver', dir: 'driver' },
  { id: 'infini-goal-tool', dir: 'tool' },
  { id: 'infini-goal-command', dir: 'command' },
  { id: 'infini-goal-ui', dir: 'client-ui' },
]

/**
 * Resolve one row's built host entry.
 * @param row - row declaration.
 * @returns absolute path of the built entry.
 * @throws when the package was not built yet.
 */
function entryOf(row) {
  const entry = join(ROOT, 'packages', row.dir, 'lib', 'index.js')
  if (!existsSync(entry)) throw new Error(`missing built entry ${entry} (run "pnpm build" first)`)
  return entry
}

/** Render one row as YAML, using the absolute built entry path. */
function renderRow(row) {
  const lines = [
    `    - id: ${row.id}`,
    `      name: ${JSON.stringify(entryOf(row))}`,
  ]
  if (row.config !== undefined) {
    lines.push('      config:')
    for (const [key, value] of Object.entries(row.config)) {
      lines.push(`        ${key}: ${JSON.stringify(value)}`)
    }
  }
  return lines.join('\n')
}

try {
  const text = [
    '# Generated by `pnpm dev:patch` — development overlay for the infini-goal plugin suite.',
    '# Insert rows use absolute built entry paths, so no profile install is required.',
    '- insert:',
    ...ROWS.map(renderRow),
    '',
  ].join('\n')

  await mkdir(dirname(OUT), { recursive: true })
  await writeFile(OUT, text)
  console.log(text)
  console.log(`wrote ${OUT}`)
} catch (error) {
  console.error(`dev-patch: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
