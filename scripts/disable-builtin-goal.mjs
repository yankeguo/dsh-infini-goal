#!/usr/bin/env node
/**
 * Write (or remove) a marked patch block that disables the built-in dsh-goal
 * mode in one DSH profile.
 *
 * Prefer the optional bundle (`@yankeguo/dsh-disable-goal-bundle`) when it is
 * installed: that keeps the profile patch clean and toggles from the Plugins
 * UI. This script remains the choice for custom profiles and for inspecting
 * exactly what the bundle generates.
 *
 * Why not just disable the `goal` host row? The shipped Web surface keeps the
 * `goals` SERVICE on the host plane and mounts `command-goal` / `tool-goal`
 * per agent preset; removing the service makes every preset binding fail with
 * `agent-preset/invalid: ... waiting for goals`. So this script disables only
 * the automatic-round driver and the client GoalBar, and drops the
 * command/tool children from the shipped preset child lists.
 *
 * Usage:
 *   node scripts/disable-builtin-goal.mjs --print
 *   node scripts/disable-builtin-goal.mjs --write \
 *     --profile-patch ~/.dsh/profiles/desktop/cordis.patch.yml
 *   node scripts/disable-builtin-goal.mjs --remove \
 *     --profile-patch ~/.dsh/profiles/desktop/cordis.patch.yml
 *   node scripts/disable-builtin-goal.mjs --print --presets-dir /path/to/presets
 */
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join, resolve } from 'node:path'
import {
  BLOCK_BEGIN,
  BLOCK_END,
  DEFAULT_ASAR,
  buildDisableGoalEntries,
  loadPresetPatches,
  readDshVersion,
  removeGeneratedBlock,
} from './lib/disable-goal.mjs'

const USAGE = `Usage:
  node scripts/disable-builtin-goal.mjs --print
  node scripts/disable-builtin-goal.mjs --write --profile-patch <path>
  node scripts/disable-builtin-goal.mjs --remove --profile-patch <path>

Options:
  --print                  print the generated patch block (default)
  --write                  append/replace the generated block in --profile-patch
  --remove                 remove the generated block from --profile-patch
  --profile-patch <path>   profile patch file (default ~/.dsh/profiles/desktop/cordis.patch.yml)
  --app-asar <path>        installed app.asar (default ${DEFAULT_ASAR})
  --presets-dir <path>     read preset patches from a directory instead of app.asar
  --exclude <names>        comma-separated preset names to skip
`

/** Parse `--flag value` options and boolean flags. */
function parseArgs(argv) {
  const options = {
    mode: 'print',
    profilePatch: join(homedir(), '.dsh', 'profiles', 'desktop', 'cordis.patch.yml'),
    appAsar: DEFAULT_ASAR,
    presetsDir: undefined,
    exclude: [],
  }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    switch (arg) {
      case '--print':
        options.mode = 'print'
        break
      case '--write':
        options.mode = 'write'
        break
      case '--remove':
        options.mode = 'remove'
        break
      case '--profile-patch':
        options.profilePatch = resolve(argv[++index])
        break
      case '--app-asar':
        options.appAsar = resolve(argv[++index])
        break
      case '--presets-dir':
        options.presetsDir = resolve(argv[++index])
        break
      case '--exclude':
        options.exclude = argv[++index].split(',').map(name => name.trim()).filter(Boolean)
        break
      case '-h':
      case '--help':
        process.stdout.write(USAGE)
        process.exit(0)
      // fallthrough for unknown flags
      default:
        throw new Error(`unknown argument: ${arg}`)
    }
  }
  return options
}

/** Remove a previously generated marked block from a profile patch. */
function removeBlock(options) {
  if (!existsSync(options.profilePatch)) throw new Error(`profile patch not found: ${options.profilePatch}`)
  const text = readFileSync(options.profilePatch, 'utf8')
  if (!text.includes(BLOCK_BEGIN)) {
    console.log('no generated block found; nothing to remove')
    return
  }
  backup(options.profilePatch)
  writeFileSync(options.profilePatch, removeGeneratedBlock(text))
  console.log(`removed generated block from ${options.profilePatch}`)
}

/** Print the block, or write it into the profile patch. */
function writeOrPrintBlock(options) {
  const presetPatches = loadPresetPatches(options)
  if (presetPatches.size === 0) throw new Error('all presets were excluded; nothing to generate')
  const version = options.presetsDir === undefined ? readDshVersion(options.appAsar) : 'unknown'
  const block = [
    BLOCK_BEGIN,
    '# Generated by scripts/disable-builtin-goal.mjs; re-run after a DSH upgrade.',
    `# DSH runtime: ${version}`,
    '# The `goal` service itself stays mounted: shipped Web surfaces mount',
    '# command-goal/tool-goal per agent preset, and removing the service makes',
    '# preset activation fail with "waiting for goals".',
    ...buildDisableGoalEntries(presetPatches),
    BLOCK_END,
    '',
  ].join('\n')

  if (options.mode === 'print') {
    process.stdout.write(block)
    return
  }

  if (!existsSync(options.profilePatch)) throw new Error(`profile patch not found: ${options.profilePatch}`)
  const original = readFileSync(options.profilePatch, 'utf8')
  const withoutBlock = removeGeneratedBlock(original).replace(/\n+$/, '\n')
  backup(options.profilePatch)
  writeFileSync(options.profilePatch, `${withoutBlock}\n${block}`)
  console.log(`wrote generated block to ${options.profilePatch}`)
}

/** Back up a file before rewriting it. */
function backup(path) {
  const stamp = new Date().toISOString().replaceAll(':', '-')
  const target = `${path}.bak-disable-goal-${stamp}`
  copyFileSync(path, target)
  console.log(`backed up ${path} -> ${target}`)
}

try {
  const options = parseArgs(process.argv.slice(2))
  if (options.mode === 'remove') removeBlock(options)
  else writeOrPrintBlock(options)
} catch (error) {
  console.error(`disable-builtin-goal: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
